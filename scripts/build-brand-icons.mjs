// Emits src/core/brand-icons.ts — the SVG path + brand colour for every service
// in the split-tunnel catalog, taken from `simple-icons` (same source
// awg-manager uses). Only the slugs we actually show are inlined, so the bundle
// stays small. Re-run after changing the catalog:
//
//   node scripts/build-brand-icons.mjs
import * as si from "simple-icons";
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Service key (or label) → simple-icons slug, where the name doesn't match. */
const MANUAL = {
  x_com: "x", twitter: "x", youtube: "youtube", ea_app: "ea", battle_net: "battledotnet",
  google_play: "googleplay", amazon_aws: "amazonwebservices", xiaomi: "xiaomi",
  mi_home: "xiaomi", jetbrains: "jetbrains", fast_com: "fastly", speedtest: "speedtest",
  cs2: "counterstrike", pubg: "pubg", apex_legends: "ea", faceit: "faceit",
  openai: "openai", anthropic: "anthropic", gemini: "googlegemini", grok: "x",
  copilot: "githubcopilot", perplexity: "perplexity", telegram: "telegram",
  whatsapp: "whatsapp", viber: "viber", tiktok: "tiktok", twitch: "twitch",
  instagram: "instagram", discord: "discord", steam: "steam", cloudflare: "cloudflare",
  wikipedia: "wikipedia", nvidia: "nvidia", samsung: "samsung", adobe: "adobe",
  atlassian: "atlassian", binance: "binance", paypal: "paypal", vimeo: "vimeo",
  akamai: "akamai", spotify: "spotify", netflix: "netflix", github: "github",
  gitlab: "gitlab", docker: "docker", npm: "npm", reddit: "reddit", medium: "medium",
  soundcloud: "soundcloud", deezer: "deezer", signal: "signal", element: "element",
  proton: "proton", mullvad: "mullvad", torproject: "torproject", duckduckgo: "duckduckgo",
  linkedin: "linkedin", facebook: "facebook", pinterest: "pinterest", tumblr: "tumblr",
  quora: "quora", stackoverflow: "stackoverflow", huggingface: "huggingface",
  epicgames: "epicgames", riotgames: "riotgames", roblox: "roblox", ubisoft: "ubisoft",
  playstation: "playstation", xbox: "xbox", nintendo: "nintendo", crunchyroll: "crunchyroll",
};

const byTitle = new Map();
const bySlug = new Map();
for (const icon of Object.values(si)) {
  if (!icon || typeof icon !== "object" || !icon.slug) continue;
  bySlug.set(icon.slug, icon);
  byTitle.set(icon.title.toLowerCase().replace(/[^a-z0-9]/g, ""), icon);
}

/** The catalog's service ids and labels, read straight from the generated file. */
const catalog = readFileSync(join(root, "src/core/service-catalog.ts"), "utf8");
const services = [...catalog.matchAll(/"id":"([^"]+)","name":"([^"]+)"/g)].map((m) => ({ id: m[1], label: m[2] }));
const extra = readFileSync(join(root, "src/core/split-targets.ts"), "utf8");
for (const m of extra.matchAll(/(\w+):\s*\{\s*label:\s*'([^']+)'/g)) services.push({ id: m[1], label: m[2] });

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const out = {};
let matched = 0;
for (const { id, label } of services) {
  const icon =
    (MANUAL[id] && bySlug.get(MANUAL[id])) ||
    bySlug.get(norm(id)) ||
    byTitle.get(norm(label)) ||
    byTitle.get(norm(id));
  if (!icon) continue;
  const path = /\sd="([^"]+)"/.exec(icon.svg)?.[1];
  if (!path) continue;
  out[id] = { p: path, h: `#${icon.hex}` };
  matched++;
}

const body = `// Generated by scripts/build-brand-icons.mjs — do not edit.
// Brand marks for the split-tunnel picker, from simple-icons (CC0).

export interface BrandIcon {
  /** 24x24 SVG path data. */
  p: string;
  /** Official brand colour. */
  h: string;
}

export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, "src/core/brand-icons.ts"), body);
console.log(`brand-icons.ts written — ${matched} of ${services.length} services matched`);
